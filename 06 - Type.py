n1 = input('Digite a primeira coisa que vier na cabeça!')

print('o tipo primitivo',type(n1))
print('é um numero?', n1.isnumeric())
print('é alfabetico?', n1.isalpha())
print('é alfanumerico', n1.isalnum())
print('está em minusculo?', n1.islower())
print('está em maiusculo?', n1.isupper())
print('Esta Capitalizado?', n1.istitle())

print('é decimal?', n1.isdecimal())
print('é um digito?', n1.isdigit())
print('é um ascii?',n1.isascii())
print('é um identificado?',n1.isidentifier())
print('é plotavel?', n1.isprintable())
print('é somente espaços?', n1.isspace())




